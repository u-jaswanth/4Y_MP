def seed_doctors(db: Session | None = None) -> int:
    """Insert or refresh the sample directory. Safe to call repeatedly."""

    own_session = db is None
    session = db or SessionLocal()

    written = 0

    try:
        for entry in DOCTORS:
            point = coordinates_for(entry["area"])

            values = {
                **entry,
                "city": CITY,
                "latitude": point[0] if point else None,
                "longitude": point[1] if point else None,
            }

            doctor = (
                session.query(Doctor)
                .filter(Doctor.slug == values["slug"])
                .first()
            )

            if doctor is None:
                session.add(Doctor(**values))
            else:
                for key, value in values.items():
                    setattr(doctor, key, value)

            written += 1

        session.commit()

    except Exception as error:  # noqa: BLE001
        session.rollback()
        print(f"[doctors] Could not seed the sample directory ({error}).")
        written = 0

    finally:
        if own_session:
            session.close()

    return written
